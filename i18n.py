def translate(lang, key, **kw):
    pair = STRINGS.get(key)
    if not pair:
        return key
    s = pair[0] if lang == "it" else pair[1]
    try:
        return s.format(**kw) if kw else s
    except (KeyError, IndexError):
        return s
